#!/usr/bin/env python3
"""Generate icrc_crc32_pkg.sv: the CRC-32 (Ethernet, reflected, polynomial
0xEDB88320) of a block of B bytes as XOR equations, for icrc.sv.

For a state c and a block d of B bytes (d[7:0] is the first byte on the wire,
each byte taken least significant bit first), the CRC after the block is

    crc32_f<B>(c) ^ crc32_g<B>(d)

f is the effect of the state (32 x 32), g the effect of the data (32 x 8B);
both are linear over GF(2), so every output bit is the parity of a fixed
subset of the inputs. Run: gen_icrc_crc32_pkg.py > icrc_crc32_pkg.sv
"""
import sys

POLY = 0xEDB88320
BLOCKS = [128, 64, 32, 16, 8, 4]


def equations(nbytes):
    # variables: 0..31 the state, 32.. the data bits
    state = [1 << i for i in range(32)]
    for byte in range(nbytes):
        for bit in range(8):
            state[0] ^= 1 << (32 + byte * 8 + bit)  # c ^= data bit (LSB first)
            low = state[0]
            state = state[1:] + [0]                  # c >>= 1
            for i in range(32):
                if POLY >> i & 1:
                    state[i] ^= low                  # ^= POLY if the bit shifted out was 1
    f = [s & 0xFFFFFFFF for s in state]
    g = [s >> 32 for s in state]
    return f, g


def check(nbytes, f, g):
    # compare with a bytewise CRC on a pseudo-random state and block
    import random
    rnd = random.Random(nbytes)
    c0 = rnd.getrandbits(32)
    data = [rnd.getrandbits(8) for _ in range(nbytes)]
    c = c0
    for b in data:
        c ^= b
        for _ in range(8):
            c = (c >> 1) ^ POLY if c & 1 else c >> 1
    d = sum(b << (8 * i) for i, b in enumerate(data))
    out = 0
    for i in range(32):
        bit = bin(c0 & f[i]).count("1") ^ bin(d & g[i]).count("1")
        out |= (bit & 1) << i
    assert out == c, (nbytes, hex(out), hex(c))


def main():
    w = sys.stdout.write
    w("// Generated by gen_icrc_crc32_pkg.py: do not edit.\n")
    w("// CRC-32 (Ethernet, reflected) of a block of B bytes:\n")
    w("//     crc_after = crc32_f<B>(crc_before) ^ crc32_g<B>(block)\n")
    w("// block[7:0] is the first byte; bytes are taken least significant bit first.\n")
    w("package icrc_crc32_pkg;\n\n")
    for b in BLOCKS:
        f, g = equations(b)
        check(b, f, g)
        w(f"function automatic logic [31:0] crc32_f{b}(input logic [31:0] c);\n")
        for i in range(31, -1, -1):
            w(f"    crc32_f{b}[{i}] = ^(c & 32'h{f[i]:08x});\n")
        w("endfunction\n\n")
        w(f"function automatic logic [31:0] crc32_g{b}(input logic [{8 * b - 1}:0] d);\n")
        for i in range(31, -1, -1):
            w(f"    crc32_g{b}[{i}] = ^(d & {8 * b}'h{g[i]:0{2 * b}x});\n")
        w("endfunction\n\n")
    w("endpackage\n")


if __name__ == "__main__":
    main()
